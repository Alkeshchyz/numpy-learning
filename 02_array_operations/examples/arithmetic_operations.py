import numpy as np

a = np.array([10, 20, 30])
b = np.array([2, 4, 5])

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("floor Division:", a // b)
print("Modulus:", a % b)
print("Exponentiation:", a ** b)
print("square root of a:", np.sqrt(a))
print("power of a to 2:", np.power(a, 2))